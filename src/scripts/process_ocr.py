def _slice_box_into_lines(box_img: Image.Image, min_line_h: int = 10) -> list[Image.Image]:
    """Slice a multi-line box image into horizontal line image slices using projection profile."""
    img_gray = box_img.convert("L")
    arr = np.array(img_gray)
    binary = (arr < 185).astype(np.uint8)
    row_counts = np.sum(binary, axis=1)

    in_line = False
    lines = []
    start = 0
    thresh = max(5, int(box_img.width * 0.01))
    for y, count in enumerate(row_counts):
        if count > thresh and not in_line:
            in_line = True
            start = y
        elif count <= thresh and in_line:
            in_line = False
            if y - start >= min_line_h:
                lines.append((max(0, start - 2), min(box_img.height, y + 2)))
    if in_line and len(row_counts) - start >= min_line_h:
        lines.append((max(0, start - 2), min(box_img.height, len(row_counts))))

    if len(lines) <= 1:
        return [box_img]
    return [box_img.crop((0, y1, box_img.width, y2)) for y1, y2 in lines]


def _is_heading_like(txt: str, block: dict, page_w: float) -> bool:
    if not txt:
        return False
    if txt.startswith('#'):
        return True
    clean = txt.lstrip('#').strip()
    if not clean:
        return False
    if re.match(r'^(?:第[一二三四五六七八九十\d]+[章节回集卷篇]|(?:[（(]?[一二三四五六七八九十\d]+[)）]?[.、\s]?))', clean):
        return True
    if HeadingDetector:
        dummy = {"surya_text": clean, "bbox": block.get("bbox", [0, 0, 0, 0])}
        if HeadingDetector.detect_block_level(dummy, page_width=page_w) > 0:
            return True
    if len(clean) <= 20 and not any(p in clean for p in ('。', '，', '；', '！', '？', ':', '：')):
        func_count = sum(1 for w in '的了在是有与和于为以从到对' if w in clean)
        if func_count <= 1:
            return True
    return False


def _merge_wrapping_paragraphs(para_blocks: list, page_w: float = 1000.0, line_height_thresh: float = 35.0) -> list:
    """
    Merges vertically adjacent text blocks that represent the same paragraph
    broken by an image cutout or text-wrapping around an illustration.
    """
    if not para_blocks:
        return para_blocks

    terminal_chars = {'。', '！', '？', '；', '…', ':', '：'}
    merged = []
    for blk in para_blocks:
        if not merged:
            merged.append(blk)
            continue

        prev = merged[-1]
        prev_label = prev.get("original_label", "").lower()
        curr_label = blk.get("original_label", "").lower()

        if prev_label in ("text", "paragraph", "section-header") and curr_label in ("text", "paragraph"):
            prev_txt = prev.get("surya_text", "").strip()
            curr_txt = blk.get("surya_text", "").strip()

            if _is_heading_like(prev_txt, prev, page_w) or _is_heading_like(curr_txt, blk, page_w):
                merged.append(blk)
                continue

            prev_last_char = prev_txt[-1] if prev_txt else ""
            ends_mid_sentence = (
                prev_last_char not in terminal_chars
                or prev_last_char in ('《', '“', '（', '(', '[', '〈')
            )
            prev_bbox = prev.get("bbox", [0, 0, 0, 0])
            curr_bbox = blk.get("bbox", [0, 0, 0, 0])
            y_gap = curr_bbox[1] - prev_bbox[3]

            if ends_mid_sentence and 0 <= y_gap <= line_height_thresh:
                prev["surya_text"] = prev_txt + curr_txt
                prev["bbox"] = [
                    min(prev_bbox[0], curr_bbox[0]),
                    prev_bbox[1],
                    max(prev_bbox[2], curr_bbox[2]),
                    curr_bbox[3]
                ]
                continue

        merged.append(blk)
    return merged


def extract_block_text(block):
    """
    Extract full concatenated text content from a layout block.
    """
    if "surya_text" in block:
        return block["surya_text"].strip()
    text_parts = []
    for line in block.get("lines", []):
        for span in line.get("spans", []):
            content = span.get("content", "")
            if content:
                text_parts.append(content)
    return "".join(text_parts).strip()


def is_strong_citation_text(text: str) -> bool:
    """
    Check if a text candidate has strong literature citation characteristics:
    e.g., book marks 《...》, journal tags [M]/[J]/[Z]/[D], '出版社', '年版', '第X页', 'pp.'.
    """
    if not text:
        return False
    citation_patterns = [
        r'《[^》]+》',
        r'\[[A-Z]\]',
        r'(?:出版社|出版|Press)',
        r'(?:\d{4}\s*年\s*版|\d{4}\s*年)',
        r'(?:第\s*\d+\s*页|[Pp]\.?\s*\d+)',
        r'(?:参阅|参见|转引自|译|主编)',
    ]
    for pat in citation_patterns:
        if re.search(pat, text):
            return True
    return False


def parse_footnote_entries(text):
    """
    Parse one or more footnote entries from a footnote block text.
    Supports circled numbers (①..㊿), brackets ([1]), superscript digits,
    '注1:', '(1)', '1.' prefixes.
    """
    if not text or not text.strip():
        return []

    pattern = re.compile(
        r'(?:^|\n)\s*([①-⑩\u2460-\u24ff\u2780-\u2793\u3251-\u325f]|[\[［〔【]\s*\d+\s*[\]］〕】]|[⁰¹²³⁴⁵⁶⁷⁸⁹]+|注\s*\d+[:：.]?|[（(]?\s*\d+\s*[)）][.、]?|\d+[.、\s])\s*'
    )

    all_matches = list(pattern.finditer(text))
    if not all_matches:
        return [{"id": 1, "raw_marker": "", "content": text.strip()}]

    def get_marker_type(m_str):
        if not m_str: return "empty"
        m_str = m_str.strip()
        if re.match(r'^[①-⑩\u2460-\u24ff\u2780-\u2793\u3251-\u325f]', m_str): return "circled"
        if re.match(r'^[\[［〔【]', m_str): return "bracket"
        if re.match(r'^[⁰¹²³⁴⁵⁶⁷⁸⁹]', m_str): return "superscript"
        if m_str.startswith('注'): return "zhu"
        if m_str.startswith('(') or m_str.startswith('（'): return "paren"
        return "dot"

    first_type = get_marker_type(all_matches[0].group(1))
    matches = [m for m in all_matches if get_marker_type(m.group(1)) == first_type]

    entries = []
    for i, m in enumerate(matches):
        marker_str = m.group(1).strip()
        start = m.end()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        content = text[start:end].strip()

        num_val = 1
        if MarkerDetector:
            if marker_str and marker_str[0] in MarkerDetector.CIRCLED_NUMBERS:
                num_val = MarkerDetector.CIRCLED_NUMBERS.index(marker_str[0]) + 1
            elif all(c in MarkerDetector.SUPERSCRIPT_DIGITS for c in marker_str if c):
                num_val = int("".join(str(MarkerDetector.SUPERSCRIPT_DIGITS.index(c)) for c in marker_str))
            else:
                digits = re.findall(r'\d+', marker_str)
                if digits:
                    num_val = int(digits[0])
        else:
            digits = re.findall(r'\d+', marker_str)
            if digits:
                num_val = int(digits[0])

        entries.append({
            "id": num_val,
            "raw_marker": marker_str,
            "content": content
        })

    return entries


def sort_blocks_2d_reading_order(para_blocks, page_w, page_h):
    """
    智能 2D 自然閱讀順序排序：
    1. 過濾極外側邊緣切口章名標籤與極底端純頁碼
    2. 自動辨識圖文卡片（垂直緊密相連之圖片與標題/說明文字群組）
    3. 依水平橫向分帶 (Band) 劃分多欄/網格卡片，橫帶內依欄位由左至右、欄內自上而下排版
    """
    if not para_blocks:
        return []

    def x_overlap(b1, b2):
        return max(0, min(b1[2], b2[2]) - max(b1[0], b2[0]))

    # 過濾邊界切口裝飾文字（如極右外側豎向章名 '第一章'）
    valid_blocks = []
    for b in para_blocks:
        bbox = b["bbox"]
        w = bbox[2] - bbox[0]
        # 右側邊界極窄文字（豎排章名切口標）
        if bbox[0] > page_w * 0.88 and w < 25 and b.get("original_label") in ("text", "caption", "header"):
            txt = b.get("surya_text", "").replace(" ", "")
            if re.match(r'^第[一二三四五六七八九十]+章$', txt):
                continue
        # 底端獨立頁碼
        if bbox[1] > page_h * 0.90 and (bbox[3] - bbox[1]) < 25:
            txt = b.get("surya_text", "").strip()
            if re.match(r'^\d{1,4}$', txt):
                continue
        valid_blocks.append(b)

    # 初步按 (y0, x0) 排序
    valid_blocks.sort(key=lambda b: (b["bbox"][1], b["bbox"][0]))

    # 聚類圖文卡片或多行欄位
    clusters = []
    for b in valid_blocks:
        b_bbox = b["bbox"]
        b_is_img = b.get("original_label") in ["image", "figure", "chart", "vision_figure", "picture"]
        placed = False
        for cl in clusters:
            cl_bbox = cl["bbox"]
            has_img = any(item.get("original_label") in ["image", "figure", "chart", "vision_figure", "picture"] for item in cl["items"])
            if b_is_img and has_img:
                continue # 一個圖文卡片最多包含一張主圖
            overlap = x_overlap(b_bbox, cl_bbox)
            min_w = min(b_bbox[2] - b_bbox[0], cl_bbox[2] - cl_bbox[0])
            v_gap = b_bbox[1] - cl_bbox[3]
            if min_w > 0 and (overlap / min_w) > 0.4 and -10 <= v_gap <= 25:
                b_w = b_bbox[2] - b_bbox[0]
                cl_w = cl_bbox[2] - cl_bbox[0]
                if b_w < page_w * 0.6 and cl_w < page_w * 0.6:
                    cl["items"].append(b)
                    cl["bbox"] = [
                        min(cl_bbox[0], b_bbox[0]),
                        min(cl_bbox[1], b_bbox[1]),
                        max(cl_bbox[2], b_bbox[2]),
                        max(cl_bbox[3], b_bbox[3])
                    ]
                    placed = True
                    break
        if not placed:
            clusters.append({
                "bbox": list(b_bbox),
                "items": [b]
            })

    # 將卡片聚類依垂直投影重疊劃分為水平行帶 (Horizontal Bands)
    bands = []
    for cl in sorted(clusters, key=lambda c: c["bbox"][1]):
        placed = False
        for band in bands:
            band_y0, band_y1 = band["y0"], band["y1"]
            ov = max(0, min(cl["bbox"][3], band_y1) - max(cl["bbox"][1], band_y0))
            min_h = min(cl["bbox"][3] - cl["bbox"][1], band_y1 - band_y0)
            if min_h > 0 and (ov / min_h) > 0.35:
                band["clusters"].append(cl)
                band["y0"] = min(band["y0"], cl["bbox"][1])
                band["y1"] = max(band["y1"], cl["bbox"][3])
                placed = True
                break
        if not placed:
            bands.append({
                "y0": cl["bbox"][1],
                "y1": cl["bbox"][3],
                "clusters": [cl]
            })

    # 行帶自上而下；帶內欄位由左至右；欄內自上而下
    ordered_blocks = []
    for band in bands:
        band["clusters"].sort(key=lambda c: c["bbox"][0])
        for cl in band["clusters"]:
            cl["items"].sort(key=lambda b: b["bbox"][1])
            ordered_blocks.extend(cl["items"])

    return ordered_blocks


def process_page_footnotes(
    page_info,
    page_num,
    previous_open_footnote,
    audit_records,
    style_mapping=None,
    no_footnote=False,
    enable_footnotes: bool = True
):
    """
    Process layout blocks of a single page (text & footnotes ONLY):
    1. Separate candidate footnote blocks from definite body blocks while tracking indices.
    2. Handle cross-page continuation.
    3. Match body anchors or verify strong citation characteristics.
    4. If unmatched and lacking citation semantics, preserve block in original reading order.
    5. Render page markdown with Pandoc footnotes [^n].
    Image extraction is handled separately by pdf_image_extractor.py.
    """
    if not enable_footnotes:
        no_footnote = True
    elif no_footnote:
        enable_footnotes = False

    if style_mapping is None:
        style_mapping = {}

    page_size = page_info.get("page_size", [1000, 1000])
    page_h = page_size[1] if len(page_size) >= 2 else 1000
    para_blocks = page_info.get("para_blocks", [])

    # Keep track of blocks by original order
    # item: {"block": block, "is_candidate_fn": bool, "orig_idx": int}
    indexed_blocks = []
    for idx, block in enumerate(para_blocks):
        b_type = block.get("type")
        orig_label = block.get("original_label", "")
        bbox = block.get("bbox", [0, 0, 0, 0])
        y0 = bbox[1] if len(bbox) >= 2 else 0

        is_fn = False
        # ✅ 僅在啟用註腳時才將區塊標記為候選註腳；否則一律視為正文
        if enable_footnotes:
            is_fn = orig_label in ["footnote", "vision_footnote"]
            if not is_fn and y0 > (page_h * 0.72) and b_type not in ["Title", "Table", "Figure"]:
                blk_txt = extract_block_text(block)
                if _FOOTNOTE_PREFIX_RE.search(blk_txt):
                    is_fn = True

        indexed_blocks.append({
            "block": block,
            "is_candidate_fn": is_fn,
            "orig_idx": idx
        })

    # Render candidate body text for marker detection
    initial_body_blocks = [item["block"] for item in indexed_blocks if not item["is_candidate_fn"]]
    candidate_fn_items = [item for item in indexed_blocks if item["is_candidate_fn"]]

    # Extract footnote entries
    new_open_footnote = None
    parsed_entries_map = {}  # orig_idx -> entries

    for fn_item in candidate_fn_items:
        blk_txt = extract_block_text(fn_item["block"]).strip()
        entries = parse_footnote_entries(blk_txt)
        parsed_entries_map[fn_item["orig_idx"]] = entries

    def render_blocks(blocks_with_idx):
        rendered = []
        for item in blocks_with_idx:
            blk = item["block"]
            orig_label = blk.get("original_label", "").lower()
            is_img = orig_label in ["image", "figure", "chart", "vision_figure", "picture"]
            
            if is_img:
                md_text = "![img]()"
            elif orig_label == "table":
                blk["type"] = "Table"
                raw_tbl = (blk.get("surya_text") or "").strip()
                if raw_tbl.startswith("|"):
                    md_text = raw_tbl
                else:
                    tbl_lines = [ln.strip() for ln in raw_tbl.splitlines() if ln.strip()]
                    if len(tbl_lines) >= 2 and any(re.search(r"\s{2,}|\t", ln) for ln in tbl_lines):
                        split_rows = [re.split(r"\s{2,}|\t", ln) for ln in tbl_lines]
                        max_c = max(len(r) for r in split_rows)
                        if max_c >= 2:
                            norm_rows = [r + [""] * (max_c - len(r)) for r in split_rows]
                            md_lines = [
                                "| " + " | ".join(norm_rows[0]) + " |",
                                "| " + " | ".join(["---"] * max_c) + " |",
                            ]
                            for r in norm_rows[1:]:
                                md_lines.append("| " + " | ".join(r) + " |")
                            md_text = "\n".join(md_lines)
                        else:
                            md_text = raw_tbl
                    else:
                        md_text = raw_tbl
            else:
                md_text = blk.get("surya_text", "")
            rendered.append({"orig_idx": item["orig_idx"], "block": blk, "md": md_text})
        return rendered

    # Initial body markdown list
    rendered_initial = render_blocks([item for item in indexed_blocks if not item["is_candidate_fn"]])

    # Apply Heading Detection to upgrade headings based on geometry & regex
    try:
        from src.founder_tools.core.heading_detector import HeadingDetector
        for item in rendered_initial:
            blk = item["block"]
            if blk.get("type") == "Table":
                continue

            level = HeadingDetector.detect_block_level(blk, page_width=600.0)
            if level > 0:
                clean_text = item["md"].lstrip('#').strip()
                prefix = '#' * level
                custom_style = style_mapping.get(f'h{level}')
                if custom_style:
                    item["md"] = f"{prefix} {clean_text} {{custom-style=\"{custom_style}\"}}"
                else:
                    item["md"] = f"{prefix} {clean_text}"
    except ImportError:
        pass

    final_footnotes = []
    blocks_to_restore = []

    # Evaluate each candidate footnote block
    for fn_item in candidate_fn_items:
        orig_idx = fn_item["orig_idx"]
        entries = parsed_entries_map.get(orig_idx, [])
        blk_txt = extract_block_text(fn_item["block"])

        # Check cross-page continuation
        if entries and not entries[0]["raw_marker"] and previous_open_footnote:
            previous_open_footnote["content"] += " " + entries[0]["content"]
            audit_records.append({
                "page": page_num,
                "type": "CONTINUATION",
                "id": previous_open_footnote["id"],
                "msg": f"跨頁接續注釋：已自動拼接至前頁注釋 [{previous_open_footnote['id']}] 末尾。"
            })
            entries = entries[1:]

        block_has_matched_anchor = False
        valid_entries_in_block = []

        for entry in entries:
            fn_id = entry["id"]
            marker_str = entry["raw_marker"]
            content = entry["content"]
            fn_ref_tag = f"[^p{page_num}_{fn_id}]"

            matched = False
            
            # Determine if the marker is 'weak' (just digits, punctuation, or spaces).
            # Strong markers like ① or [1] are safe for naive string replacement.
            is_weak_marker = bool(not marker_str or re.fullmatch(r'[\d.、\s()]+', marker_str))
            
            # Check in body markdown
            for p_item in rendered_initial:
                if not is_weak_marker and marker_str and marker_str in p_item["md"]:
                    idx = p_item["md"].find(marker_str)
                    # 註腳正文上標應依附於詞句中或句末，絕非獨立段落起始的條目編號 (例如 ②將藥材...)
                    if idx == 0 and not is_strong_citation_text(p_item["md"]):
                        continue
                    p_item["md"] = p_item["md"][:idx] + fn_ref_tag + p_item["md"][idx + len(marker_str):]
                    matched = True
                    break
                elif MarkerDetector:
                    detected = MarkerDetector.detect(p_item["md"], "auto")
                    for d in detected:
                        if d.number == fn_id:
                            p_item["md"] = p_item["md"][:d.start_char] + fn_ref_tag + p_item["md"][d.end_char:]
                            matched = True
                            break
                    if matched:
                        break

            if matched:
                block_has_matched_anchor = True
                valid_entries_in_block.append(entry)
                audit_records.append({
                    "page": page_num,
                    "type": "MATCHED",
                    "id": fn_id,
                    "msg": f"注釋 [{fn_id}] 雙向匹配成功，已替換正文標記。"
                })
            else:
                # Missing anchor in body: Check if it's genuinely a citation
                if is_strong_citation_text(content):
                    # Genuine footnote with lost OCR superscript -> safely append reference
                    target_p_idx = -1
                    for idx in range(len(rendered_initial) - 1, -1, -1):
                        if rendered_initial[idx]["md"].strip():
                            target_p_idx = idx
                            break
                    if target_p_idx >= 0:
                        rendered_initial[target_p_idx]["md"] = rendered_initial[target_p_idx]["md"].rstrip() + fn_ref_tag
                    else:
                        # Append a new item
                        rendered_initial.append({"orig_idx": -1, "md": fn_ref_tag})

                    valid_entries_in_block.append(entry)
                    audit_records.append({
                        "page": page_num,
                        "type": "FALLBACK",
                        "id": fn_id,
                        "msg": f"⚠️ 警告：文獻注釋 [{fn_id}] 正文未偵測到上標，已安全降級插入至當頁段落末端。內容：{content[:35]}..."
                    })
                else:
                    # It is regular body text (e.g. ordered list items like ⑤执行...)
                    # DO NOT convert to footnote! Mark block for restoration.
                    pass

        if valid_entries_in_block:
            final_footnotes.extend(valid_entries_in_block)
            new_open_footnote = valid_entries_in_block[-1]
        else:
            # Entire block is body text -> restore to body!
            blocks_to_restore.append(fn_item)

    # If blocks need to be restored to original reading order, re-render body with them included
    if blocks_to_restore:
        for item in blocks_to_restore:
            item["is_candidate_fn"] = False

        # Sort all blocks by original index to ensure pristine reading order
        final_body_items = sorted([item for item in indexed_blocks if not item["is_candidate_fn"]], key=lambda x: x["orig_idx"])
        rendered_initial = render_blocks(final_body_items)

        # Re-apply matched footnote references to the re-rendered body
        for fn in final_footnotes:
            fn_id = fn["id"]
            marker_str = fn["raw_marker"]
            fn_ref_tag = f"[^p{page_num}_{fn_id}]"
            is_weak_marker = bool(not marker_str or _WEAK_MARKER_CHECK_RE.fullmatch(marker_str))
            for p_item in rendered_initial:
                if not is_weak_marker and marker_str and marker_str in p_item["md"]:
                    p_item["md"] = p_item["md"].replace(marker_str, fn_ref_tag, 1)
                    break
                elif is_weak_marker and marker_str:
                    safe_pat = re.compile(r'(?<!\d)' + re.escape(marker_str) + r'(?!\d)')
                    new_text, n_subs = safe_pat.subn(fn_ref_tag, p_item["md"], count=1)
                    if n_subs > 0:
                        p_item["md"] = new_text
                        break
                elif MarkerDetector:
                    detected = MarkerDetector.detect(p_item["md"], "auto")
                    found = False
                    for d in detected:
                        if d.number == fn_id:
                            p_item["md"] = p_item["md"][:d.start_char] + fn_ref_tag + p_item["md"][d.end_char:]
                            found = True
                            break
                    if found:
                        break

    # Return list of dicts: [{"orig_idx": idx, "md": text, "block": blk}, ...]
    body_markdown_list = [{"orig_idx": item["orig_idx"], "md": item["md"], "block": item.get("block", {})} for item in rendered_initial]
    return body_markdown_list, final_footnotes, new_open_footnote


