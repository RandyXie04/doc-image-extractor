def _get_ocr_marker_type(m_str: str) -> str:
    if not m_str:
        return "empty"
    m_str = m_str.strip()
    if re.match(r'^[①-⑩\u2460-\u24ff\u2780-\u2793\u3251-\u325f]', m_str):
        return "circled"
    if re.match(r'^[\[［〔【]', m_str):
        return "bracket"
    if re.match(r'^[⁰¹²³⁴⁵⁶⁷⁸⁹]', m_str):
        return "superscript"
    if m_str.startswith('注'):
        return "zhu"
    if m_str.startswith(('(', '（')):
        return "paren"
    if re.match(r'^[a-jA-J]', m_str):
        return "alpha"
    return "dot"


def _resolve_ocr_marker_number(marker_str: str) -> int:
    _ensure_detectors_loaded()
    if MarkerDetector:
        if marker_str and marker_str[0] in MarkerDetector.CIRCLED_NUMBERS:
            return MarkerDetector.CIRCLED_NUMBERS.index(marker_str[0]) + 1
        if all(c in MarkerDetector.SUPERSCRIPT_DIGITS for c in marker_str if c):
            return int("".join(str(MarkerDetector.SUPERSCRIPT_DIGITS.index(c)) for c in marker_str))
    alpha_m = re.search(r'[a-zA-Z]', marker_str)
    if alpha_m:
        return ord(alpha_m.group(0).lower()) - ord('a') + 1
    digits = re.findall(r'\d+', marker_str)
    return int(digits[0]) if digits else 1


def parse_footnote_entries(text):
    """
    Parse one or more footnote entries from a footnote block text.
    Supports circled numbers (①..㊿), brackets ([1]), superscript digits,
    '注1:', '(1)', '1.' prefixes.
    """
    if not text or not text.strip():
        return []

    raw_matches = list(_OCR_FOOTNOTE_ENTRY_PATTERN.finditer(text))
    all_matches = [m for m in raw_matches if is_valid_footnote_split_match(text, m)]
    if not all_matches:
        return [{"id": 1, "raw_marker": "", "content": text.strip()}]

    first_type = _get_ocr_marker_type(all_matches[0].group(1))
    matches = [m for m in all_matches if _get_ocr_marker_type(m.group(1)) == first_type]

    entries = []
    leading_text = text[:matches[0].start()].strip()
    if leading_text and not re.match(r'^(?:注[释釋]?|脚[注釋]?|参考[文献獻]|References?|NOTES?)[:：]?\s*$', leading_text, re.I):
        entries.append({"id": 1, "raw_marker": "", "content": leading_text})

    for i, m in enumerate(matches):
        marker_str = m.group(1).strip()
        start = m.end()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        content = text[start:end].strip()
        num_val = _resolve_ocr_marker_number(marker_str)
        prev_content = str(entries[-1].get("content", "")) if entries else ""

        if entries and is_citation_continuation_marker(marker_str, num_val, prev_content):
            sep = "" if prev_content.endswith((":", "：", ";", "；")) else " "
            entries[-1]["content"] = (prev_content + sep + marker_str + (" " + content if content else "")).strip()
            continue

        entries.append({"id": num_val, "raw_marker": marker_str, "content": content})

    return entries


def sort_blocks_2d_reading_order(para_blocks, page_w, page_h):
    """
    智能 2D 自然閱讀順序排序：
    1. 過濾極外側邊緣切口章名標籤
    2. 自動辨識圖文卡片（垂直緊密相連之圖片與標題/說明文字群組）
    3. 依水平橫向分帶 (Band) 劃分多欄/網格卡片，橫帶內依欄位由左至右、欄內自上而下排版
    """
    if not para_blocks:
        return []

    def x_overlap(b1, b2):
        return max(0, min(b1[2], b2[2]) - max(b1[0], b2[0]))

    # 過濾邊界切口裝飾文字（如極右外側豎向章名 '第一章'）
    valid_blocks = []
    for b in para_blocks:
        bbox = b["bbox"]
        w = bbox[2] - bbox[0]
        # 右側邊界極窄文字（豎排章名切口標）
        if bbox[0] > page_w * 0.88 and w < 25 and b.get("original_label") in ("text", "caption", "header"):
            txt = b.get("surya_text", "").replace(" ", "")
            if re.match(r'^第[一二三四五六七八九十]+章$', txt):
                continue
        valid_blocks.append(b)

    # 初步按 (y0, x0) 排序
    valid_blocks.sort(key=lambda b: (b["bbox"][1], b["bbox"][0]))

    # 聚類圖文卡片或多行欄位
    clusters = []
    for b in valid_blocks:
        b_bbox = b["bbox"]
        b_is_img = b.get("original_label") in ["image", "figure", "chart", "vision_figure", "picture"]
        placed = False
        for cl in clusters:
            cl_bbox = cl["bbox"]
            has_img = any(item.get("original_label") in ["image", "figure", "chart", "vision_figure", "picture"] for item in cl["items"])
            if b_is_img and has_img:
                continue # 一個圖文卡片最多包含一張主圖
            overlap = x_overlap(b_bbox, cl_bbox)
            min_w = min(b_bbox[2] - b_bbox[0], cl_bbox[2] - cl_bbox[0])
            v_gap = b_bbox[1] - cl_bbox[3]
            if min_w > 0 and (overlap / min_w) > 0.4 and -10 <= v_gap <= 25:
                b_w = b_bbox[2] - b_bbox[0]
                cl_w = cl_bbox[2] - cl_bbox[0]
                if b_w < page_w * 0.6 and cl_w < page_w * 0.6:
                    cl["items"].append(b)
                    cl["bbox"] = [
                        min(cl_bbox[0], b_bbox[0]),
                        min(cl_bbox[1], b_bbox[1]),
                        max(cl_bbox[2], b_bbox[2]),
                        max(cl_bbox[3], b_bbox[3])
                    ]
                    placed = True
                    break
        if not placed:
            clusters.append({
                "bbox": list(b_bbox),
                "items": [b]
            })

    # 將卡片聚類依垂直投影重疊劃分為水平行帶 (Horizontal Bands)
    bands = []
    for cl in sorted(clusters, key=lambda c: c["bbox"][1]):
        placed = False
        for band in bands:
            band_y0, band_y1 = band["y0"], band["y1"]
            ov = max(0, min(cl["bbox"][3], band_y1) - max(cl["bbox"][1], band_y0))
            min_h = min(cl["bbox"][3] - cl["bbox"][1], band_y1 - band_y0)
            if min_h > 0 and (ov / min_h) > 0.35:
                band["clusters"].append(cl)
                band["y0"] = min(band["y0"], cl["bbox"][1])
                band["y1"] = max(band["y1"], cl["bbox"][3])
                placed = True
                break
        if not placed:
            bands.append({
                "y0": cl["bbox"][1],
                "y1": cl["bbox"][3],
                "clusters": [cl]
            })

    # 行帶自上而下；帶內欄位由左至右；欄內自上而下
    ordered_blocks = []
    for band in bands:
        band["clusters"].sort(key=lambda c: c["bbox"][0])
        for cl in band["clusters"]:
            cl["items"].sort(key=lambda b: b["bbox"][1])
            ordered_blocks.extend(cl["items"])

    return ordered_blocks


def _is_ocr_candidate_footnote_block(block: dict, page_h: float, enable_footnotes: bool) -> bool:
    if not enable_footnotes:
        return False
    orig_label = block.get("original_label", "")
    if orig_label in ["footnote", "vision_footnote"]:
        return True
    bbox = block.get("bbox", [0, 0, 0, 0])
    y0 = bbox[1] if len(bbox) >= 2 else 0
    if y0 > (page_h * 0.72) and block.get("type") not in ["Title", "Table", "Figure"]:
        blk_txt = extract_block_text(block)
        return bool(_FOOTNOTE_PREFIX_RE.search(blk_txt) or is_strong_citation_text(blk_txt))
    return False


def _format_ocr_table_markdown(raw_tbl: str) -> str:
    if raw_tbl.startswith("|"):
        return raw_tbl
    tbl_lines = [ln.strip() for ln in raw_tbl.splitlines() if ln.strip()]
    if len(tbl_lines) < 2 or not any(re.search(r"\s{2,}|\t", ln) for ln in tbl_lines):
        return raw_tbl
    split_rows = [re.split(r"\s{2,}|\t", ln) for ln in tbl_lines]
    max_c = max(len(r) for r in split_rows)
    if max_c < 2:
        return raw_tbl
    norm_rows = [r + [""] * (max_c - len(r)) for r in split_rows]
    md_lines = [
        "| " + " | ".join(norm_rows[0]) + " |",
        "| " + " | ".join(["---"] * max_c) + " |",
    ]
    md_lines.extend("| " + " | ".join(r) + " |" for r in norm_rows[1:])
    return "\n".join(md_lines)


def _render_ocr_body_blocks(blocks_with_idx: list[dict]) -> list[dict]:
    rendered = []
    for item in blocks_with_idx:
        blk = item["block"]
        orig_label = blk.get("original_label", "").lower()
        if orig_label in ["image", "figure", "chart", "vision_figure", "picture"]:
            md_text = "![img]()"
        elif orig_label == "table":
            blk["type"] = "Table"
            md_text = _format_ocr_table_markdown((blk.get("surya_text") or "").strip())
        else:
            md_text = blk.get("surya_text", "")
        rendered.append({"orig_idx": item["orig_idx"], "block": blk, "md": md_text})
    return rendered


def _classify_ocr_footnote_entry(
    entry: dict, initial_body_texts: list[str], page_num: int, audit_records: list
) -> bool:
    fn_id = entry["id"]
    marker_str = entry["raw_marker"]
    content = entry["content"]
    matched = any(
        has_ocr_marker_match_in_block(
            b_txt,
            marker_str,
            fn_id,
            prev_context=initial_body_texts[b_idx - 1].rstrip() if b_idx > 0 else "",
            marker_detector=MarkerDetector,
        )
        for b_idx, b_txt in enumerate(initial_body_texts)
    )
    if matched:
        entry["is_fallback_citation"] = False
        audit_records.append({
            "page": page_num,
            "type": "MATCHED",
            "id": fn_id,
            "msg": f"注釋 [{fn_id}] 雙向匹配成功，已替換正文標記。",
        })
        return True
    if is_strong_citation_text(content):
        entry["is_fallback_citation"] = True
        audit_records.append({
            "page": page_num,
            "type": "FALLBACK",
            "id": fn_id,
            "msg": f"⚠️ 警告：文獻注釋 [{fn_id}] 正文未偵測到上標，已安全降級插入至當頁段落末端。內容：{content[:35]}...",
        })
        return True
    return False


def _resolve_ocr_candidate_footnotes(
    indexed_blocks: list[dict], page_num: int, previous_open_footnote: Any, audit_records: list
) -> tuple[list[dict], Any]:
    candidate_fn_items = [item for item in indexed_blocks if item["is_candidate_fn"]]
    initial_body_texts = [item["block"].get("surya_text", "") for item in indexed_blocks if not item["is_candidate_fn"]]
    final_footnotes: list[dict] = []
    new_open_footnote = None

    for fn_item in candidate_fn_items:
        blk_txt = extract_block_text(fn_item["block"]).strip()
        entries = parse_footnote_entries(blk_txt)
        if entries and not entries[0]["raw_marker"] and previous_open_footnote:
            previous_open_footnote["content"] += " " + entries[0]["content"]
            audit_records.append({
                "page": page_num,
                "type": "CONTINUATION",
                "id": previous_open_footnote["id"],
                "msg": f"跨頁接續注釋：已自動拼接至前頁注釋 [{previous_open_footnote['id']}] 末尾。",
            })
            entries = entries[1:]

        valid_entries = [
            e for e in entries if _classify_ocr_footnote_entry(e, initial_body_texts, page_num, audit_records)
        ]
        if valid_entries:
            final_footnotes.extend(valid_entries)
            new_open_footnote = valid_entries[-1]
        else:
            fn_item["is_candidate_fn"] = False

    return final_footnotes, new_open_footnote


def _replace_ocr_footnote_in_item(
    p_item: dict, marker_str: str, fn_id: int, fn_ref_tag: str, prev_context: str
) -> bool:
    new_md, replaced = try_replace_primary_marker(
        p_item["md"],
        marker_str,
        fn_ref_tag,
        preceding_context=prev_context,
        use_ocr_weak_check=True,
        require_citation_at_start=True,
    )
    if replaced:
        p_item["md"] = new_md
        return True
    if not MarkerDetector:
        return False
    for d in MarkerDetector.detect(p_item["md"], "auto"):
        if d.number == fn_id:
            p_item["md"] = p_item["md"][:d.start_char] + fn_ref_tag + p_item["md"][d.end_char:]
            return True
    return False


def _attach_ocr_fallback_footnote(rendered_body: list[dict], fn_id: int, fn_ref_tag: str) -> None:
    non_empty_indices = [idx for idx in range(len(rendered_body) - 1, -1, -1) if rendered_body[idx]["md"].strip()]
    if not non_empty_indices:
        rendered_body.append({"orig_idx": -1, "block": {}, "md": fn_ref_tag})
        return
    target_idx = non_empty_indices[0]
    target_md, replaced = try_replace_alpha_fallback(rendered_body[target_idx]["md"], fn_id, fn_ref_tag)
    rendered_body[target_idx]["md"] = target_md if replaced else (rendered_body[target_idx]["md"].rstrip() + fn_ref_tag)


def _apply_ocr_footnotes_to_rendered_body(
    rendered_body: list[dict], final_footnotes: list[dict], page_num: int
) -> None:
    for fn in final_footnotes:
        fn_id = fn["id"]
        marker_str = fn["raw_marker"]
        fn_ref_tag = f"[^p{page_num}_{fn_id}]"
        replaced = False
        for p_idx, p_item in enumerate(rendered_body):
            prev_context = rendered_body[p_idx - 1]["md"].rstrip() if p_idx > 0 else ""
            if _replace_ocr_footnote_in_item(p_item, marker_str, fn_id, fn_ref_tag, prev_context):
                replaced = True
                break
        if not replaced and fn.get("is_fallback_citation"):
            _attach_ocr_fallback_footnote(rendered_body, fn_id, fn_ref_tag)


def _build_ocr_ai_heading_candidate(item: dict, page_w: float, page_num: int) -> dict | None:
    candidate_text = (item.get("md") or "").strip()
    if not (2 <= len(candidate_text) <= 55):
        return None
    if re.search(r'[。！？；.]$', candidate_text) or candidate_text.startswith(("|", "![")):
        return None
    blk = item["block"]
    bbox = blk.get("bbox", [0, 0, 0, 0])
    spans = [span for line in blk.get("lines", []) for span in line.get("spans", [])]
    sizes = [float(span.get("size", 0.0) or 0.0) for span in spans]
    return {
        "paragraph_id": f"ocr-{page_num}-{item['orig_idx']}",
        "text": candidate_text,
        "font_size": round(sum(sizes) / len(sizes), 2) if sizes else None,
        "is_bold": any(bool(span.get("bold") or (span.get("flags", 0) & 16)) for span in spans),
        "is_centered": abs(((bbox[0] + bbox[2]) / 2.0) - (page_w / 2.0)) < (page_w * 0.08),
    }


def _detect_ocr_headings_and_collect_candidates(
    rendered_body: list[dict], page_w: float, page_num: int, style_mapping: dict
) -> list[dict]:
    ai_candidate_items: list[dict] = []
    try:
        from src.founder_tools.core.heading_detector import HeadingDetector
    except ImportError:
        return ai_candidate_items

    for item in rendered_body:
        blk = item["block"]
        if blk.get("type") == "Table":
            continue
        level = HeadingDetector.detect_block_level(blk, page_width=page_w)
        if level > 0:
            clean_text = item["md"].lstrip('#').strip()
            custom_style = style_mapping.get(f'h{level}')
            item["md"] = f"{'#' * level} {clean_text} {{custom-style=\"{custom_style}\"}}" if custom_style else f"{'#' * level} {clean_text}"
        else:
            cand = _build_ocr_ai_heading_candidate(item, page_w, page_num)
            if cand is not None:
                ai_candidate_items.append(cand)
    return ai_candidate_items


def _apply_single_ocr_gemma_review(
    item: dict, review: dict, page_num: int, style_mapping: dict, audit_records: list
) -> None:
    if review.get("source") != "gemma":
        if review.get("ai_status"):
            audit_records.append({
                "page": page_num,
                "type": "AI_LAYOUT_STATUS",
                "id": review.get("paragraph_id"),
                "status": review.get("ai_status"),
                "model": DEFAULT_GEMMA_MODEL,
            })
        return
    if review.get("role") == "heading" and review.get("level") in (1, 2, 3):
        level = review["level"]
        clean_text = (item.get("md") or "").lstrip("#").strip()
        custom_style = style_mapping.get(f"h{level}")
        item["md"] = f"{'#' * level} {clean_text} {{custom-style=\"{custom_style}\"}}" if custom_style else f"{'#' * level} {clean_text}"
    elif review.get("role") == "quote" and style_mapping.get("kaiti"):
        item["md"] = f'::: {{custom-style="{style_mapping["kaiti"]}"}}\n{item["md"]}\n:::'
    item["layout_ai"] = {
        "source": "gemma",
        "role": review.get("role"),
        "level": review.get("level"),
        "confidence": review.get("confidence"),
        "reason": review.get("reason", ""),
    }
    audit_records.append({
        "page": page_num,
        "type": "AI_LAYOUT",
        "source": "gemma",
        "id": review.get("paragraph_id"),
        "role": review.get("role"),
        "level": review.get("level"),
        "confidence": review.get("confidence"),
        "reason": review.get("reason", ""),
    })


def _apply_ocr_gemma_reviews(
    rendered_body: list[dict], ai_candidate_items: list[dict], page_num: int, style_mapping: dict, audit_records: list
) -> None:
    if not ai_candidate_items:
        return
    try:
        from src.scripts.gemma_layout_assistant import review_uncertain_layout
    except ImportError:
        return
    ai_by_id = {item["paragraph_id"]: item for item in review_uncertain_layout(ai_candidate_items[:12])}
    for item in rendered_body:
        review = ai_by_id.get(f"ocr-{page_num}-{item['orig_idx']}")
        if review and review.get("ai_status") != "model_unavailable":
            _apply_single_ocr_gemma_review(item, review, page_num, style_mapping, audit_records)


def _apply_ocr_body_style(rendered_body: list[dict], style_mapping: dict) -> None:
    body_style = style_mapping.get("body")
    if not body_style:
        return
    for item in rendered_body:
        text = (item.get("md") or "").strip()
        block_label = item["block"].get("original_label", "").lower()
        if text and not text.startswith(("#", "|", "![", ":::", "[^")) and block_label not in ("caption", "figure", "image", "table"):
            item["md"] = f'::: {{custom-style="{body_style}"}}\n{text}\n:::'
            item["body_style_applied"] = True


def process_page_footnotes(
    page_info,
    page_num,
    previous_open_footnote,
    audit_records,
    style_mapping=None,
    no_footnote=False,
    enable_footnotes: bool = True
):
    """
    Process layout blocks of a single page (text & footnotes ONLY):
    1. Separate candidate footnote blocks from definite body blocks while tracking indices.
    2. Handle cross-page continuation and match body anchors or citation semantics.
    3. Restore unmatched blocks back to body stream without wiping heading or Word styles.
    4. Render final page markdown with Pandoc footnotes [^n], headings (#) and custom styles.
    Image extraction is handled separately by pdf_image_extractor.py.
    """
    effective_footnotes = enable_footnotes and not no_footnote
    style_map = style_mapping or {}

    _ensure_detectors_loaded()
    page_size = page_info.get("page_size", [1000, 1000])
    page_w = float(page_size[0]) if len(page_size) >= 1 else 1000.0
    page_h = float(page_size[1]) if len(page_size) >= 2 else 1000.0
    para_blocks = page_info.get("para_blocks", [])

    indexed_blocks = [
        {
            "block": block,
            "is_candidate_fn": _is_ocr_candidate_footnote_block(block, page_h, effective_footnotes),
            "orig_idx": idx,
        }
        for idx, block in enumerate(para_blocks)
    ]

    final_footnotes, new_open_footnote = _resolve_ocr_candidate_footnotes(
        indexed_blocks, page_num, previous_open_footnote, audit_records
    )

    final_body_items = sorted(
        [item for item in indexed_blocks if not item["is_candidate_fn"]],
        key=lambda x: x["orig_idx"],
    )
    rendered_body = _render_ocr_body_blocks(final_body_items)

    _apply_ocr_footnotes_to_rendered_body(rendered_body, final_footnotes, page_num)
    ai_candidates = _detect_ocr_headings_and_collect_candidates(rendered_body, page_w, page_num, style_map)
    _apply_ocr_gemma_reviews(rendered_body, ai_candidates, page_num, style_map, audit_records)
    _apply_ocr_body_style(rendered_body, style_map)

    body_markdown_list = [
        {"orig_idx": item["orig_idx"], "md": item["md"], "block": item.get("block", {})}
        for item in rendered_body
    ]
    return body_markdown_list, final_footnotes, new_open_footnote


def generate_audit_report(pdf_name, total_pages, audit_records, report_path):
    """
    Generate structured footnote review audit report (footnote_review.txt).
    """
    total_fns = len([r for r in audit_records if r["type"] in ["MATCHED", "FALLBACK"]])
    matched_fns = len([r for r in audit_records if r["type"] == "MATCHED"])
    fallback_fns = len([r for r in audit_records if r["type"] == "FALLBACK"])
    continuation_fns = len([r for r in audit_records if r["type"] == "CONTINUATION"])
    warning_fns = len([r for r in audit_records if r["type"] == "FALLBACK"])

    now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    lines = [
        "=" * 80,
        "書籍 PDF OCR 腳注提取與雙向審計覆核報告",
        f"處理時間：{now_str}",
        f"處理檔案：{pdf_name}",
        "=" * 80,
        "【統計總覽】",
        f"  總處理頁數    ：{total_pages} 頁",
        f"  提取腳注總數  ：{total_fns} 條",
        f"  精準雙向匹配  ：{matched_fns} 條",
        f"  安全降級錨定  ：{fallback_fns} 條",
        f"  跨頁拼接接續  ：{continuation_fns} 條",
        f"  需人工覆核警告：{warning_fns} 處",
        "-" * 80,
        "【逐頁審計明細】",
    ]

    if not audit_records:
        lines.append("  (本檔案無偵測到注釋或無異常項目)")
    else:
        for r in audit_records:
            icon = "✅" if r["type"] == "MATCHED" else "⚠️"
            lines.append(f"  [第 {r['page']:03d} 頁] {icon} {r['msg']}")

    lines.extend([
        "=" * 80,
        "說明：標記為 ⚠️ 警告的項目，表示因 OCR 上標模糊或原書缺標記，系統已自動將其",
        "保存在該頁末尾，未丟失任何文字。非文獻之正文編號已完整保留於內文原處。",
        "=" * 80,
        ""
    ])

    with open(report_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def build_ocr_layout_contracts(pages_data: list[dict[str, Any]]) -> list[Any]:
    """
    Constructs and validates strict `LayoutRecordContract` objects from assembled OCR `pages_data`
    to enforce P2/P3 Zero Raw-Dict schema parity with `book_layout_extractor.py`.
    """
    from src.extraction.contracts import validate_layout_records

    raw_records: list[dict[str, Any]] = []
    for p in pages_data:
        p_num = int(p.get("page_num", 1))
        for md_dict in p.get("body", []):
            orig_idx = int(md_dict.get("orig_idx", 0))
            md_item = str(md_dict.get("md", "")).strip()
            blk = md_dict.get("block") or {}
            bbox_raw = blk.get("bbox")
            bbox_list = [float(x) for x in bbox_raw[:4]] if isinstance(bbox_raw, (list, tuple)) and len(bbox_raw) >= 4 else [0.0, 0.0, 0.0, 0.0]
            orig_label = str(blk.get("original_label", "")).lower()

            if md_item == "![img]()" or orig_label in ("picture", "figure", "image"):
                raw_records.append({
                    "type": "figure",
                    "page_num": p_num,
                    "block_idx": orig_idx,
                    "raw_md": md_item or "![img]()",
                    "bbox": bbox_list,
                })
            elif orig_label == "table" or (md_item.startswith("|") and "\n|" in md_item):
                raw_records.append({
                    "type": "table",
                    "raw_md": md_item,
                    "caption_text": "",
                    "page_num": p_num,
                    "bbox": bbox_list,
                })
            elif md_item.startswith("#"):
                hashes = len(md_item) - len(md_item.lstrip("#"))
                lvl = min(max(hashes, 1), 6)
                title_str = md_item.lstrip("#").strip()
                raw_records.append({
                    "type": "heading",
                    "level": lvl,
                    "title": title_str,
                    "raw_text": md_item,
                    "page_num": p_num,
                    "bbox": bbox_list,
                })
            elif md_item:
                raw_records.append({
                    "type": "paragraph",
                    "raw_text": md_item,
                    "page_num": p_num,
                    "bbox": bbox_list,
                })

        for fn_idx, fn in enumerate(p.get("footnotes", []), start=1):
            fn_id_raw = fn.get("id", fn_idx)
            try:
                fn_id_int = int(str(fn_id_raw).strip())
            except Exception:
                fn_id_int = fn_idx
            fn_content = str(fn.get("content", ""))
            if fn_content:
                raw_records.append({
                    "type": "footnote",
                    "fn_id": fn_id_int,
                    "tag": f"[^p{p_num}_{fn_id_raw}]",
                    "content": fn_content,
                    "page_num": p_num,
                })

    return validate_layout_records(raw_records)


def _collect_image_blocks_from_surya(pdf_info_list: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Collect image/figure blocks from OCR page metadata for raster image extraction."""
    image_labels = {"image", "figure", "chart", "vision_figure", "picture"}
    blocks: list[dict[str, Any]] = []
    for page_info in pdf_info_list:
        page_idx = int(page_info.get("page_idx", 0))
        page_num = page_idx + 1
        page_size = page_info.get("page_size", [1000.0, 1000.0])
        page_w = float(page_size[0]) if len(page_size) >= 1 else 1000.0
        page_h = float(page_size[1]) if len(page_size) >= 2 else 1000.0
        for block_idx, block in enumerate(page_info.get("para_blocks", [])):
            orig_label = str(block.get("original_label", "")).lower()
            bbox = block.get("bbox", [])
            if orig_label in image_labels and isinstance(bbox, (list, tuple)) and len(bbox) >= 4:
                blocks.append({
                    "page_num": page_num,
                    "block_idx": block_idx,
                    "bbox": [float(v) for v in bbox[:4]],
                    "page_w": page_w,
                    "page_h": page_h,
                })
    return blocks


