def _clean_hallucinations(text: str) -> str:
    """Detects and removes repetitive hallucinated text generated by the OCR model."""
    if not text:
        return text
    text_len = len(text)
    if text_len > 15:
        # If very few unique characters are used in a long text block, it's a hallucination
        unique_chars = len(set(text))
        if unique_chars / text_len < 0.15:
            return ""
        # Check for repeating n-grams
        if _HALLUCINATION_REPEAT_RE.search(text):
            return ""
    return text

