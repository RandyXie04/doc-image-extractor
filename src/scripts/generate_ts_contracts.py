def _json_schema_prop_to_ts(prop: Dict[str, Any], defs: Dict[str, Any]) -> str:
    """Converts a single JSON Schema property node to a TypeScript type expression."""
    if "$ref" in prop:
        ref_name = prop["$ref"].split("/")[-1]
        return ref_name

    if "const" in prop:
        val = prop["const"]
        return f'"{val}"' if isinstance(val, str) else str(val).lower()

    if "enum" in prop:
        vals = prop["enum"]
        return " | ".join(f'"{v}"' if isinstance(v, str) else str(v) for v in vals)

    if "anyOf" in prop:
        sub_types = [_json_schema_prop_to_ts(sub, defs) for sub in prop["anyOf"]]
        deduped: List[str] = []
        for st in sub_types:
            if st not in deduped:
                deduped.append(st)
        return " | ".join(deduped)

    schema_type = prop.get("type")
    if schema_type == "string":
        return "string"
    if schema_type in ("integer", "number"):
        return "number"
    if schema_type == "boolean":
        return "boolean"
    if schema_type == "null":
        return "null"
    if schema_type == "array":
        items = prop.get("items", {})
        item_ts = _json_schema_prop_to_ts(items, defs)
        if "|" in item_ts:
            return f"Array<{item_ts}>"
        return f"{item_ts}[]"
    if schema_type == "object":
        return "Record<string, unknown>"

    return "unknown"


def _model_to_ts_interface(model_cls: Type[BaseModel]) -> str:
    schema = model_cls.model_json_schema()
    defs = schema.get("$defs", {})
    props = schema.get("properties", {})
    required_set = set(schema.get("required", []))

    lines = [f"export interface {model_cls.__name__} {{"]
    for field_name, field_schema in props.items():
        ts_type = _json_schema_prop_to_ts(field_schema, defs)
        is_req = field_name in required_set or "default" in field_schema
        opt_suffix = "" if is_req else "?"
        lines.append(f"  readonly {field_name}{opt_suffix}: {ts_type};")
    lines.append("}")
    return "\n".join(lines)


def generate_typescript_contracts_source() -> str:
    """Generates the full TypeScript contract file content from Pydantic models."""
    header = [
        "/**",
        " * AUTO-GENERATED BY `src/scripts/generate_ts_contracts.py` — DO NOT EDIT MANUALLY.",
        " * Source of Truth: `src/web/schemas.py` & `src/extraction/contracts.py` (Pydantic v2 Strict Mode).",
        " */",
        "",
    ]
    blocks = [_model_to_ts_interface(m) for m in EXPORTED_MODELS]

    unions = [
        "export type PropagationPayload =",
        "  | RuleFirstPropagationPayload",
        "  | VlmContinuationPropagationPayload;",
        "",
        "export type LayoutRecordContract =",
        "  | ParagraphLayoutContract",
        "  | HeadingLayoutContract",
        "  | TableLayoutContract",
        "  | FigureLayoutContract",
        "  | FootnoteLayoutContract;",
        "",
        "export type PodSessionPhase =",
        "  | { readonly phase: \"idle\" }",
        "  | { readonly phase: \"compiling_blueprint\"; readonly seedFileName: string; readonly pdfFileName?: string }",
        "  | { readonly phase: \"blueprint_ready\"; readonly response: PodCompileBlueprintResponse }",
        "  | { readonly phase: \"propagating\"; readonly sessionId: string; readonly payload: PropagationPayload }",
        "  | { readonly phase: \"completed\"; readonly response: PodPropagateResponse }",
        "  | { readonly phase: \"error\"; readonly message: string };",
        "",
    ]
    return "\n".join(header) + "\n\n".join(blocks) + "\n\n" + "\n".join(unions)


def sync_typescript_contracts(output_path: Path | None = None, check_only: bool = False) -> Path:
    """Writes or verifies `frontend/src/types/contracts.ts`."""
    project_root = Path(__file__).resolve().parent.parent.parent
    target = output_path or (project_root / "frontend" / "src" / "types" / "contracts.ts")
    expected_content = generate_typescript_contracts_source()

    if check_only:
        if not target.exists():
            raise RuntimeError(f"Missing generated TypeScript contract file: {target}")
        current = target.read_text(encoding="utf-8")
        if current != expected_content:
            raise RuntimeError(f"TypeScript contract drift detected in {target}. Run generate_ts_contracts.py.")
        return target

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(expected_content, encoding="utf-8")
    return target


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate or verify TypeScript contracts from Pydantic schemas.")
    parser.add_argument("--check", action="store_true", help="Fail if contracts.ts is out of sync")
    args = parser.parse_args()
    out = sync_typescript_contracts(check_only=args.check)
    print(f"[TS Contracts] {'Verified' if args.check else 'Generated'}: {out}")


if __name__ == "__main__":
    main()
